<script>
    (function() {
        function setupInfiniteMarquees() {
            const wrappers = document.querySelectorAll('.category-marquee-wrapper');
            wrappers.forEach(wrapper => {
                const track = wrapper.querySelector('.category-marquee-track');
                if (!track) return;

                const primaryGroup = track.querySelector('.category-marquee-group');
                if (!primaryGroup) return;

                // Bersihkan klon lama jika ada
                track.querySelectorAll('.category-marquee-group:not(:first-child)').forEach(el => el
                    .remove());

                const wrapperWidth = wrapper.offsetWidth;
                const groupWidth = primaryGroup.offsetWidth;

                if (wrapperWidth === 0 || groupWidth === 0) return;

                // Samakan kecepatan fisik (pixel per detik) untuk semua baris
                // Baik baris yang isinya 5 icon maupun 28 icon akan bergerak dengan kecepatan yang sama persis
                const pixelsPerSecond =
                    45; // Ubah nilai ini jika ingin lebih lambat (misal 35) atau lebih cepat (misal 55)
                const duration = groupWidth / pixelsPerSecond;
                wrapper.style.setProperty('--marquee-duration', `${duration}s`);

                // Logika: Klon grup secara otomatis hingga panjangnya minimal 2x lebar kontainer + 1 grup
                const minTotalWidth = (wrapperWidth * 2) + groupWidth;
                let currentWidth = groupWidth;

                while (currentWidth < minTotalWidth) {
                    const clone = primaryGroup.cloneNode(true);
                    clone.setAttribute('aria-hidden', 'true');
                    track.appendChild(clone);
                    currentWidth += groupWidth;
                }
            });
        }

        if (document.readyState === 'complete') {
            setupInfiniteMarquees();
        } else {
            window.addEventListener('load', setupInfiniteMarquees);
            document.addEventListener('DOMContentLoaded', setupInfiniteMarquees);
        }

        let resizeTimer;
        window.addEventListener('resize', () => {
            clearTimeout(resizeTimer);
            resizeTimer = setTimeout(setupInfiniteMarquees, 150);
        });
    })();
</script>
